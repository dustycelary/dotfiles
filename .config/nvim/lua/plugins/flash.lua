-- flash.nvim — 2-character fast motion navigation & Treesitter jump targets.
return {
	"folke/flash.nvim",
	event = "VeryLazy",
	opts = {
		modes = {
			-- disable flash's takeover of native f/F/t/T/;/, motions
			-- (this repo already handles those via quick-scope + nvim-treesitter-textobjects)
			char = { enabled = false },
		},
	},
	keys = {
		{
			"s",
			mode = { "n", "x", "o" },
			function()
				require("flash").jump()
			end,
			desc = "Flash jump",
		},
		{
			"S",
			mode = { "n", "x", "o" },
			function()
				require("flash").treesitter()
			end,
			desc = "Flash Treesitter",
		},
		{
			"r",
			mode = "o",
			function()
				require("flash").remote()
			end,
			desc = "Remote Flash",
		},
		{
			"R",
			mode = { "o", "x" },
			function()
				require("flash").treesitter_search()
			end,
			desc = "Treesitter Search",
		},
		{
			"<c-s>",
			mode = { "c" },
			function()
				require("flash").toggle()
			end,
			desc = "Toggle Flash Search",
		},
	},
}
